export function countryOf(code: string): string {
  return COUNTRY_NAMES[code.slice(0, 3)] ?? "Diğer";
}

/** Kütüphaneleri ülkelere göre gruplar, ülke adına göre sıralar. */
export function librariesByCountry(): { country: string; libraries: Library[] }[] {
  const groups = new Map<string, Library[]>();
  for (const lib of LIBRARIES) {
    const country = countryOf(lib.code);
    groups.set(country, [...(groups.get(country) ?? []), lib]);
  }
  return [...groups.entries()]
    .map(([country, libraries]) => ({ country, libraries }))
    .sort((x, y) => x.country.localeCompare(y.country, "tr"));
}
